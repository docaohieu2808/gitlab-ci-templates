#!/usr/bin/env python3
"""Assemble auto-pipeline.yml and the CI/CD component from the fragments in jobs/.

jobs/ is the single source of truth. Two files are generated from it:

  auto-pipeline.yml
      variables.yml + stages.yml + every job fragment, concatenated.
  templates/auto-detect-build-test-deploy/template.yml
      a `spec:` header whose inputs mirror jobs/variables.yml, a `---` line, a
      `variables:` block that maps each input to its variable, then the same
      stages and job fragments.

Usage:
  scripts/build-pipelines-from-fragments.py          write both files
  scripts/build-pipelines-from-fragments.py --check  exit 1 if either file is stale
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
JOB_FRAGMENTS = [
    "jobs/stages.yml",
    "jobs/language-build-test-lint.yml",
    "jobs/security-scans.yml",
    "jobs/docker-build-and-push.yml",
    "jobs/deploy-targets.yml",
]
AUTO_PIPELINE = ROOT / "auto-pipeline.yml"
COMPONENT = ROOT / "templates/auto-detect-build-test-deploy/template.yml"

# `  NAME: "value"   # optional comment`
VARIABLE_LINE = re.compile(r'^  ([A-Z][A-Z0-9_]*): "(.*?)"\s*(?:#\s*(.*))?$')


def read(rel: str) -> str:
    return (ROOT / rel).read_text()


def parse_variables() -> list[tuple[str, str, str]]:
    found = []
    for line in read("jobs/variables.yml").splitlines():
        match = VARIABLE_LINE.match(line)
        if match:
            name, default, comment = match.groups()
            found.append((name, default, (comment or "").strip()))
    return found


def build_auto_pipeline() -> str:
    parts = [
        "# GENERATED by scripts/build-pipelines-from-fragments.py from jobs/*.yml - do not edit.\n"
        "# Zero-config pipeline: include this one file. Usage:\n"
        "#   include:\n"
        "#     - project: 'your-group/gitlab-ci-templates'\n"
        "#       ref: 1.0.0\n"
        "#       file: '/auto-pipeline.yml'\n\n",
        read("jobs/variables.yml"),
        "\n",
    ]
    parts += [read(f) + "\n" for f in JOB_FRAGMENTS]
    return "".join(parts).rstrip("\n") + "\n"


def build_component() -> str:
    variables = parse_variables()
    lines = [
        "# GENERATED by scripts/build-pipelines-from-fragments.py from jobs/*.yml - do not edit.\n",
        "# GitLab CI/CD component. Every input maps to the variable of the same name in\n",
        "# upper case; see jobs/variables.yml for the meaning of each one.\n",
        "spec:\n",
        "  inputs:\n",
    ]
    for name, default, comment in variables:
        description = comment or f"Sets the {name} variable"
        lines.append(f"    {name.lower()}:\n")
        lines.append(f'      default: "{default}"\n')
        lines.append(f'      description: "{description.replace(chr(34), chr(39))}"\n')
    lines.append("---\n")
    lines.append("variables:\n")
    for name, _, _ in variables:
        lines.append(f'  {name}: "$[[ inputs.{name.lower()} ]]"\n')
    lines.append("\n")
    lines += [read(f) + "\n" for f in JOB_FRAGMENTS]
    return "".join(lines).rstrip("\n") + "\n"


def main() -> int:
    outputs = {AUTO_PIPELINE: build_auto_pipeline(), COMPONENT: build_component()}
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} - run scripts/build-pipelines-from-fragments.py", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
